"use client";

// shadcn/ui's Dropdown Menu (Base UI version), styled with Showthrough's design tokens.
// Same component names and props as https://ui.shadcn.com/docs/components/base/dropdown-menu
// so examples from the shadcn docs work as written.

import * as React from "react";
import { Menu as MenuPrimitive } from "@base-ui/react/menu";

// Base UI accepts className as a string or as a function of the component's state.
type ClassName<State> = string | ((state: State) => string | undefined) | undefined;
function cn<State>(base: string, className?: ClassName<State>): string | ((state: State) => string) {
  if (typeof className === "function") return (state: State) => [base, className(state)].filter(Boolean).join(" ");
  return [base, className].filter(Boolean).join(" ");
}

function DropdownMenu({ ...props }: MenuPrimitive.Root.Props) {
  return <MenuPrimitive.Root data-slot="dropdown-menu" {...props} />;
}

function DropdownMenuPortal({ ...props }: MenuPrimitive.Portal.Props) {
  return <MenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />;
}

function DropdownMenuTrigger({ ...props }: MenuPrimitive.Trigger.Props) {
  return <MenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />;
}

function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  ...props
}: MenuPrimitive.Popup.Props & Pick<MenuPrimitive.Positioner.Props, "align" | "alignOffset" | "side" | "sideOffset">) {
  return (
    <MenuPrimitive.Portal>
      <MenuPrimitive.Positioner className="isolate z-50 outline-none" align={align} alignOffset={alignOffset} side={side} sideOffset={sideOffset}>
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            "z-50 min-w-48 transition-[opacity,scale] duration-150 ease-out data-starting-style:scale-95 data-starting-style:opacity-0 data-ending-style:scale-95 data-ending-style:opacity-0 max-h-(--available-height) origin-(--transform-origin) overflow-y-auto rounded-[14px] border border-line bg-surface p-1.5 text-text shadow-pop outline-none",
            className,
          )}
          {...props}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  );
}

